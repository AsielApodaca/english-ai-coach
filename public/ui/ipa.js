/**
 * Look up the IPA transcription of a word.
 *
 * Normalizes case and strips surrounding punctuation so "Team," and "team"
 * resolve to the same entry. Returns `null` when the word is not in the
 * dictionary (the caller renders no annotation for it).
 *
 * @param {string} word
 * @returns {string|null}
 */
export function ipaFor(word) {
  const key = String(word ?? "").toLowerCase().replace(/^[^a-z0-9]+|[^a-z0-9]+$/g, "");
  if (!key) return null;
  return DICT[key] ?? null;
}